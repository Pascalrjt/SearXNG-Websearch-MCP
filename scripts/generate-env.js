#!/usr/bin/env node
/**
 * Ensures a .env file exists with a real SEARXNG_SECRET.
 * Runs automatically before `npm run docker:up`.
 *
 * - Creates .env with a random secret if it doesn't exist
 * - Replaces missing or placeholder SEARXNG_SECRET values
 * - Leaves any user-provided secret untouched
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(projectRoot, '.env');

const PLACEHOLDERS = new Set([
  'ultrasecretkey',
  'your-secret-key-change-this-in-production',
]);

const generateSecret = () => randomBytes(32).toString('hex');

if (!existsSync(envPath)) {
  writeFileSync(
    envPath,
    `# SearXNG Configuration (auto-generated by scripts/generate-env.js)\nSEARXNG_SECRET=${generateSecret()}\n`
  );
  console.log('Created .env with a randomly generated SEARXNG_SECRET.');
} else {
  const contents = readFileSync(envPath, 'utf8');
  const match = contents.match(/^SEARXNG_SECRET=(.*)$/m);
  const current = match?.[1].trim();

  if (!match || !current || PLACEHOLDERS.has(current)) {
    const secretLine = `SEARXNG_SECRET=${generateSecret()}`;
    const updated = match
      ? contents.replace(/^SEARXNG_SECRET=.*$/m, secretLine)
      : `${contents.replace(/\n?$/, '\n')}${secretLine}\n`;
    writeFileSync(envPath, updated);
    console.log(
      match
        ? 'Replaced placeholder SEARXNG_SECRET in .env with a randomly generated value.'
        : 'Added a randomly generated SEARXNG_SECRET to existing .env.'
    );
  } else {
    console.log('.env already has a SEARXNG_SECRET — leaving it untouched.');
  }
}
